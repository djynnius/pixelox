/// Check one example: it parses with clap and its values validate.
fn check_example(reg: &pixelox_core::Registry, cmd: &str) -> Result<(), String> {
    let mut cmd = cmd.trim().to_string();
    for sep in [" #", " > ", " | ", " && ", " 2>"] {
        if let Some(i) = cmd.find(sep) {
            cmd.truncate(i);
        }
    }
    let argv = shell_split(&cmd).map_err(|e| format!("{cmd}\n  {}", e.message))?;
    if argv.first().map(|s| s.as_str()) != Some("pixelox") || argv.len() < 2 || argv[1].starts_with('-') {
        return Ok(());
    }
    let (inv, _) = cli::parse_argv(reg, &argv).map_err(|e| format!("{cmd}\n  {}", e.message))?;
    let spec = reg.require(&inv.command).map_err(|e| e.message)?;
    Args::build(spec, inv.args).map(|_| ()).map_err(|e| format!("{cmd}\n  {}", e.message))
}

/// Placeholders and synopsis notation are not invocations.
fn skip(c: &str) -> bool {
    c.contains('<')
        || c.contains("...")
        || c.contains('…')
        || c.contains("$(")
        || c.contains("${")
        || c.contains("\\|")
        || c.contains(" [-")
        || c.contains("--help")
        || c.contains("--version")
        || c.split_whitespace().any(|w| w.contains('|') && !w.starts_with('\'') && !w.starts_with('"'))
}

#[test]
fn op_spec_examples_parse() {
    let reg = registry();
    let mut bad = Vec::new();
    let mut n = 0;
    for op in reg.ops() {
        for e in &op.examples {
            if skip(e.cmd) {
                continue;
            }
            n += 1;
            if let Err(m) = check_example(&reg, e.cmd) {
                bad.push(m);
            }
        }
    }
    assert!(n > 300, "only {n} examples checked");
    assert!(bad.is_empty(), "{} invalid op-spec examples:\n{}", bad.len(), bad.join("\n"));
}

/// `pixelox ...` lines in fenced blocks (with `\` continuations) and inline code spans.
fn extract(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut in_block = false;
    let mut pending = String::new();
    for raw in text.lines() {
        let line = raw.trim_start();
        if line.starts_with("```") {
            in_block = !in_block;
            continue;
        }
        if in_block {
            if !pending.is_empty() {
                pending.push(' ');
                pending.push_str(line.trim_end_matches('\\').trim());
                if !line.ends_with('\\') {
                    out.push(std::mem::take(&mut pending));
                }
            } else if line.starts_with("pixelox ") {
                if line.ends_with('\\') {
                    pending = line.trim_end_matches('\\').trim().to_string();
                } else {
                    out.push(line.to_string());
                }
            }
        } else {
            for span in line.split('`').skip(1).step_by(2) {
                if span.starts_with("pixelox ") {
                    out.push(span.to_string());
                }
            }
        }
    }
    out
}

#[test]
fn guide_and_readme_examples_parse() {
    let reg = registry();
    let root = repo_root();
    let mut files = vec![
        root.join("README.md"),
        root.join("AGENTS.md"),
        root.join("HOWTO.md"),
        root.join("skills/pixelox/SKILL.md"),
        root.join("skills/pixelox-retouch/SKILL.md"),
    ];
    fn walk(d: &Path, out: &mut Vec<PathBuf>) {
        if let Ok(rd) = std::fs::read_dir(d) {
            for e in rd.flatten() {
                let p = e.path();
                if p.is_dir() {
                    walk(&p, out);
                } else if p.extension().map(|x| x == "md").unwrap_or(false) {
                    out.push(p);
                }
            }
        }
    }
    walk(&root.join("docs/guides"), &mut files);
    walk(&Path::new(env!("CARGO_MANIFEST_DIR")).join("topics"), &mut files);
    let mut bad = Vec::new();
    let mut n = 0;
    for f in &files {
        let Ok(text) = std::fs::read_to_string(f) else { continue };
        for c in extract(&text) {
            if skip(&c) {
                continue;
            }
            n += 1;
            if let Err(m) = check_example(&reg, &c) {
                bad.push(format!("{}: {m}", f.strip_prefix(&root).unwrap_or(f).display()));
            }
        }
    }
    assert!(n > 40, "only {n} guide examples found");
    assert!(bad.is_empty(), "{} guide examples do not parse:\n{}", bad.len(), bad.join("\n"));
}

/// Places where this build intentionally differs from a PRD example, each with its reason
/// (also recorded in docs/decisions/). Anything not listed here must parse.
const PRD_DIVERGENCES: &[(&str, &str)] = &[
    (
        "render 3d --extrude brand/logo.svg --depth 40",
        "the PRD's `--size 2,1,1` primitive dimensions are `--dims X,Y,Z` (ADR 0004); --size is the output size",
    ),
    ("render 3d --primitive box --size", "primitive dimensions are --dims (ADR 0004)"),
    ("doctor --migrate-pxo", "a prose mention in §7.12 without the FILE argument"),
    ("--background '#ffffff'", "colors are --background-color; --background is the global run-as-job flag (ADR 0010)"),
];

#[test]
fn prd_examples_parse() {
    let reg = registry();
    let text = std::fs::read_to_string(repo_root().join("PRD.md")).unwrap();
    let mut bad = Vec::new();
    let mut n = 0;
    for c in extract(&text) {
        if skip(&c) || c.split_whitespace().any(|w| w.contains('|') && !w.starts_with('\'') && !w.starts_with('"')) {
            continue;
        }
        if PRD_DIVERGENCES.iter().any(|(k, _)| c.contains(k)) {
            continue;
        }
        n += 1;
        if let Err(m) = check_example(&reg, &c) {
            bad.push(m);
        }
    }
    assert!(n > 40, "only {n} PRD examples checked");
    assert!(
        bad.is_empty(),
        "{} PRD examples do not parse (fix the CLI or record a divergence):\n{}",
        bad.len(),
        bad.join("\n")
    );
}

#[test]
fn coverage_map_commands_exist() {
    let reg = registry();
    let text = std::fs::read_to_string(repo_root().join("PRD.md")).unwrap();
    let start = text.find("### 14.2 Photoshop-feature coverage map").unwrap();
    let end = start + text[start..].find("### 14.3").unwrap();
    let mut missing = Vec::new();
    for line in text[start..end].lines().filter(|l| l.starts_with('|')) {
        let cols: Vec<&str> = line.split('|').map(|c| c.trim()).collect();
        if cols.len() < 5 || cols[3] == "Pixelox" || cols[3].starts_with("---") || cols[4] == "—" {
            continue;
        }
        for span in cols[3].split('`').skip(1).step_by(2) {
            let words: Vec<&str> =
                span.split_whitespace().take_while(|w| !w.starts_with('-') && !w.contains('.') && *w != "/").collect();
            if words.is_empty() || words[0].starts_with('@') {
                continue;
            }
            // "layer *", "fx *", "transform crop / straighten": the group exists;
            // a bare "relink" names the tail of a command ("comp relink")
            let group = words[0];
            let joined = words.join(" ");
            let exists = reg.ops().iter().any(|o| {
                o.name == joined
                    || o.name.starts_with(&format!("{group} "))
                    || o.name == group
                    || o.name.ends_with(&format!(" {joined}"))
            });
            if !exists {
                missing.push(format!("{span} ({})", cols[2]));
            }
        }
    }
    assert!(missing.is_empty(), "coverage-map commands missing:\n{}", missing.join("\n"));
}
