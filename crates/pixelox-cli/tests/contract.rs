//! Contract tests (PRD §11.7): schema snapshots, the agent briefing budget, flag hygiene,
//! the documentation bar, and every `pixelox ...` example — in op specs, guides, README,
//! AGENTS.md, the skill, and the PRD — parsing against the real CLI.
//!
//! After an intentional contract change: `UPDATE_SNAPSHOTS=1 cargo test -p pixelox --test contract`.

use pixelox_cli::{batch::shell_split, cli, docgen, registry};
use pixelox_core::op::Args;
use std::path::{Path, PathBuf};

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize().unwrap()
}

fn updating() -> bool {
    std::env::var("UPDATE_SNAPSHOTS").map(|v| v == "1").unwrap_or(false)
}

#[test]
fn schema_snapshots() {
    let reg = registry();
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/snapshots/schema");
    std::fs::create_dir_all(&dir).unwrap();
    let mut failures = Vec::new();
    let mut names = Vec::new();
    for op in reg.ops() {
        names.push(op.id());
        let text = serde_json::to_string_pretty(&pixelox_core::schema::command_schema(op)).unwrap() + "\n";
        let path = dir.join(format!("{}.json", op.id()));
        if updating() {
            std::fs::write(&path, &text).unwrap();
        } else {
            match std::fs::read_to_string(&path) {
                Ok(old) if old == text => {}
                Ok(_) => failures.push(format!("{} changed", op.id())),
                Err(_) => failures.push(format!("{} has no snapshot", op.id())),
            }
        }
    }
    names.sort();
    let index = names.join("\n") + "\n";
    let ipath = dir.join("_commands.txt");
    if updating() {
        // drop snapshots of removed commands
        for e in std::fs::read_dir(&dir).unwrap().flatten() {
            let n = e.file_name().to_string_lossy().to_string();
            if n.ends_with(".json") && !names.iter().any(|c| format!("{c}.json") == n) {
                let _ = std::fs::remove_file(e.path());
            }
        }
        std::fs::write(&ipath, &index).unwrap();
    } else if std::fs::read_to_string(&ipath).ok().as_deref() != Some(index.as_str()) {
        failures.push("the command list changed".into());
    }
    assert!(failures.is_empty(), "schema contract changed (UPDATE_SNAPSHOTS=1 if intended):\n{}", failures.join("\n"));
}

#[test]
fn agent_briefing_under_budget_and_in_sync() {
    let reg = registry();
    let text = pixelox_cli::builtin::agent_briefing(&reg);
    // ~4 characters per token for English and code
    let approx_tokens = text.len() / 4;
    assert!(
        approx_tokens <= 4000,
        "describe --agent is ~{approx_tokens} tokens; the PRD budget is 4,000 (shorten summaries)"
    );
    let path = repo_root().join("docs/agents/catalog.md");
    let generated = format!("# pixelox agent briefing\n\nGenerated by `pixelox describe --agent`; CI checks it is current.\n\n```text\n{text}```\n");
    if updating() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &generated).unwrap();
    } else {
        assert_eq!(
            std::fs::read_to_string(&path).unwrap_or_default(),
            generated,
            "docs/agents/catalog.md is stale; run with UPDATE_SNAPSHOTS=1"
        );
    }
}

#[test]
fn skill_under_budget() {
    let skill = std::fs::read_to_string(repo_root().join("skills/pixelox/SKILL.md")).unwrap();
    assert!(skill.len() / 4 <= 2500, "SKILL.md is ~{} tokens; the PRD budget is 2,500", skill.len() / 4);
    // companion skills load on demand, but stay compact
    for entry in std::fs::read_dir(repo_root().join("skills")).unwrap().flatten() {
        let f = entry.path().join("SKILL.md");
        if let Ok(s) = std::fs::read_to_string(&f) {
            assert!(s.starts_with("---\nname: "), "{} needs name/description frontmatter", f.display());
            assert!(
                s.len() / 4 <= 5000,
                "{} is ~{} tokens; keep companion skills under 5,000",
                f.display(),
                s.len() / 4
            );
        }
    }
}

